import { useQuery } from "@tanstack/react-query";
import clsx from "clsx";
import {
  ArrowRight,
  Check,
  ClipboardCopy,
  Info,
  Quote,
  Sparkles,
  TriangleAlert,
} from "lucide-react";
import { useEffect, useState } from "react";
import { useNavigate, useParams } from "react-router-dom";
import { api, ApiError } from "@/api/client";
import {
  Badge,
  Button,
  EmptyState,
  ErrorState,
  PageHeader,
  Panel,
  PanelHeader,
  Skeleton,
  StatusBadge,
} from "@/components/ui";
import { CosmicOrb } from "@/components/visuals/CosmicOrb";
import { useDocumentTitle } from "@/hooks/useDocumentTitle";
import { formatArea, formatDate, formatPercent, relativeTime } from "@/lib/format";
import { toast } from "@/store/ui";

export default function InsightsPage() {
  const { analysisId } = useParams<{ analysisId?: string }>();
  const navigate = useNavigate();
  const [copied, setCopied] = useState(false);

  const completed = useQuery({
    queryKey: ["insights-candidates"],
    queryFn: () => api.listAnalyses({ status: "completed", pageSize: 30, sort: "newest" }),
    staleTime: 20_000,
  });

  const selectedId = analysisId ?? completed.data?.items[0]?.id;
  useDocumentTitle("AI insights");

  const insights = useQuery({
    queryKey: ["insights", selectedId],
    queryFn: () => api.insights(selectedId as string),
    enabled: Boolean(selectedId),
    staleTime: 30_000,
  });

  const analysis = useQuery({
    queryKey: ["analysis", selectedId],
    queryFn: () => api.getAnalysis(selectedId as string),
    enabled: Boolean(selectedId),
  });

  useEffect(() => {
    setCopied(false);
  }, [selectedId]);

  const copy = async () => {
    if (!insights.data) return;
    const text = [insights.data.headline, "", insights.data.summary, "", ...insights.data.observations.map((item) => `• ${item}`)].join("\n");
    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      toast("success", "Summary copied");
      window.setTimeout(() => setCopied(false), 2000);
    } catch {
      toast("error", "Clipboard unavailable", "Your browser blocked clipboard access.");
    }
  };

  const items = completed.data?.items ?? [];

  return (
    <div className="space-y-5">
      <PageHeader
        visual={<CosmicOrb className="size-[64px]" rings={false} particles interactive={false} speed={0.7} />}
        eyebrow="Narrative"
        title="AI insights"
        description="A readable summary of one analysis, assembled from stored statistics with fixed rules."
        actions={
          <Badge tone="primary" mono>
            deterministic · no llm
          </Badge>
        }
      />

      <div className="flex items-start gap-2 rounded-xl border border-line bg-surface/60 px-4 py-3 text-[11.5px] leading-relaxed text-muted">
        <Info className="mt-px size-3.5 shrink-0 text-violet" />
        <span>
          Nothing here is generated by a language model. Sentences are composed from the stored pixel
          counts, class transitions and area for the selected run, and every caveat the pipeline knows
          about is listed with the result.
        </span>
      </div>

      {completed.isLoading ? (
        <Panel>
          <Skeleton className="h-24 w-full" />
        </Panel>
      ) : items.length === 0 ? (
        <Panel>
          <EmptyState
            icon={<Sparkles className="size-5" />}
            title="No completed analyses"
            description="Insights are only written for runs that finished. Start a comparison, then come back."
            action={
              <Button to="/app/new" variant="primary" size="sm">
                New analysis
              </Button>
            }
          />
        </Panel>
      ) : (
        <div className="grid gap-4 lg:grid-cols-[300px_1fr]">
          <Panel padded={false} className="overflow-hidden">
            <div className="border-b border-line px-4 py-3">
              <p className="text-[11px] font-medium uppercase tracking-[0.14em] text-muted">Completed runs</p>
              <p className="mt-0.5 text-[10.5px] text-muted">{items.length} available</p>
            </div>
            <ul className="max-h-[560px] overflow-y-auto p-1.5">
              {items.map((item) => (
                <li key={item.id}>
                  <button
                    onClick={() => navigate(`/app/insights/${item.id}`)}
                    className={clsx(
                      "w-full rounded-lg px-2.5 py-2 text-left transition-colors",
                      item.id === selectedId ? "bg-surface-2" : "hover:bg-surface-2/60",
                    )}
                  >
                    <div className="flex items-start justify-between gap-2">
                      <p
                        className={clsx(
                          "max-w-[180px] truncate text-[12px]",
                          item.id === selectedId ? "text-ink" : "text-ink-soft",
                        )}
                      >
                        {item.title}
                      </p>
                      <span className="shrink-0 font-mono text-[10px] text-muted">
                        {formatPercent(item.changeRatio, 1)}
                      </span>
                    </div>
                    <div className="mt-1 flex items-center gap-2">
                      <StatusBadge status={item.status} />
                      <span className="truncate text-[10px] text-muted">{relativeTime(item.completedAt)}</span>
                    </div>
                  </button>
                </li>
              ))}
            </ul>
          </Panel>

          <div className="space-y-4">
            {insights.isError && (
              <ErrorState
                title="Could not load insights"
                message={
                  insights.error instanceof ApiError
                    ? insights.error.message
                    : insights.error instanceof Error
                      ? insights.error.message
                      : undefined
                }
                onRetry={() => insights.refetch()}
              />
            )}

            {insights.isLoading && (
              <Panel className="space-y-3">
                <Skeleton className="h-4 w-28" />
                <Skeleton className="h-8 w-3/4" />
                <Skeleton className="h-16 w-full" />
                <Skeleton className="h-24 w-full" />
              </Panel>
            )}

            {insights.data && analysis.data && (
              <>
                <Panel className="relative overflow-hidden">
                  <div className="pointer-events-none absolute -right-16 -top-16 size-48 rounded-full bg-violet/10 blur-3xl" />
                  <div className="relative">
                    <div className="flex flex-wrap items-center justify-between gap-2">
                      <Badge tone="violet" dot mono>
                        {insights.data.generatedBy} · {insights.data.source}
                      </Badge>
                      <div className="flex items-center gap-2">
                        <Button variant="ghost" size="sm" onClick={copy} icon={copied ? <Check className="size-3.5" /> : <ClipboardCopy className="size-3.5" />}>
                          {copied ? "Copied" : "Copy"}
                        </Button>
                        <Button
                          to={`/app/results/${analysis.data.id}`}
                          variant="secondary"
                          size="sm"
                          iconRight={<ArrowRight className="size-3.5" />}
                        >
                          Open result
                        </Button>
                      </div>
                    </div>

                    <h2 className="mt-5 text-[24px] font-semibold leading-snug tracking-tight text-ink">
                      {insights.data.headline}
                    </h2>
                    <p className="mt-3 max-w-2xl text-[13.5px] leading-relaxed text-ink-soft/90">
                      {insights.data.summary}
                    </p>

                    <dl className="mt-5 grid grid-cols-2 gap-px overflow-hidden rounded-xl border border-line bg-line sm:grid-cols-4">
                      {[
                        ["Changed", formatPercent(analysis.data.changeRatio, 2)],
                        ["Analysed area", formatArea(analysis.data.areaKm2)],
                        ["Dates", `${formatDate(analysis.data.dateBefore)} → ${formatDate(analysis.data.dateAfter)}`],
                        ["Completed", relativeTime(analysis.data.completedAt)],
                      ].map(([label, value]) => (
                        <div key={label} className="bg-surface px-3 py-2.5">
                          <dt className="text-[9.5px] uppercase tracking-[0.14em] text-muted">{label}</dt>
                          <dd className="mt-1 truncate font-mono text-[11px] text-ink-soft" title={value}>
                            {value}
                          </dd>
                        </div>
                      ))}
                    </dl>
                  </div>
                </Panel>

                <div className="grid gap-4 lg:grid-cols-2">
                  <Panel>
                    <PanelHeader title="Observations" description="Each sentence maps to a stored number." icon={<Quote className="size-4" />} />
                    <ul className="mt-4 space-y-3">
                      {insights.data.observations.length === 0 ? (
                        <li className="text-[12px] text-muted">No observations were produced for this run.</li>
                      ) : (
                        insights.data.observations.map((observation, index) => (
                          <li key={observation} className="flex gap-3">
                            <span className="mt-0.5 font-mono text-[10px] text-primary/70">
                              {String(index + 1).padStart(2, "0")}
                            </span>
                            <p className="text-[12.5px] leading-relaxed text-ink-soft/90">{observation}</p>
                          </li>
                        ))
                      )}
                    </ul>
                  </Panel>

                  <Panel>
                    <PanelHeader
                      title="Caveats"
                      description="What these numbers do not claim."
                      icon={<TriangleAlert className="size-4" />}
                    />
                    <ul className="mt-4 space-y-3">
                      {insights.data.caveats.map((caveat) => (
                        <li key={caveat} className="flex gap-2.5">
                          <span className="mt-[7px] size-1 shrink-0 rounded-full bg-warn/80" />
                          <p className="text-[12.5px] leading-relaxed text-muted">{caveat}</p>
                        </li>
                      ))}
                    </ul>
                  </Panel>
                </div>
              </>
            )}
          </div>
        </div>
      )}
    </div>
  );
}
